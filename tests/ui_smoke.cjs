// Run only against a disposable test instance with an admin session supplied
// through INVENTORY_SMOKE_SESSION_FILE. The scenario activates the new mode.
const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const url = process.env.INVENTORY_SMOKE_URL || 'http://127.0.0.1:8765';
  const session = JSON.parse(fs.readFileSync(process.env.INVENTORY_SMOKE_SESSION_FILE, 'utf8'));
  const browser = await chromium.launch({headless:true,
    ...(process.env.INVENTORY_SMOKE_CHROMIUM ? {executablePath:process.env.INVENTORY_SMOKE_CHROMIUM,
      args:['--no-sandbox','--no-zygote','--disable-dev-shm-usage','--single-process']} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1080}});
  await context.addCookies([{name:'inv_session',value:session.token,url}]);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const clickTab = async name => page.getByRole('button',{name,exact:true}).click();
  const saved = async () => {
    await page.waitForFunction(()=>document.querySelector('#message').textContent==='Tersimpan di server.');
    await page.locator('#message').evaluate(el=>el.textContent='');
  };
  const saveProduct = async (code, name, kind, unit, shelf, kitchen) => {
    const form=page.locator('[data-form="product"]');
    await form.locator('[name=code]').fill(code);
    await form.locator('[name=name]').fill(name);
    await form.locator('[name=kind]').selectOption(kind);
    await form.locator('[name=base_uom]').fill(unit);
    if(shelf!==null)await form.locator('[name=shelf_life_days]').fill(String(shelf));
    if(kitchen)await form.locator('[name=kitchen_id]').selectOption({label:kitchen});
    if(unit==='pcs')await form.locator('[name=discrete]').check();
    await form.getByRole('button',{name:'Simpan produk'}).click();
    await saved();
  };
  try {
    await page.goto(url+'/manufacturing');
    await page.getByRole('heading',{name:'Persiapan manufaktur'}).waitFor();
    await page.locator('[name=ack]').check();
    await page.getByRole('button',{name:'Aktifkan fondasi server'}).click();
    await saved();
    await clickTab('Dapur');
    assert.equal(await page.locator('.kitchen').count(),11);
    const warehouseForm=page.locator('[data-form=warehouse]');
    await warehouseForm.locator('[name=code]').fill('G-UI');
    await warehouseForm.locator('[name=name]').fill('Gudang uji');
    await warehouseForm.locator('[name=kind]').selectOption('kitchen');
    await warehouseForm.getByRole('button',{name:'Simpan gudang'}).click();
    await saved();
    const kitchenForm=page.locator('[data-form=kitchen]');
    await kitchenForm.locator('[name=code]').fill('DUI');
    await kitchenForm.locator('[name=name]').fill('Dapur uji');
    await kitchenForm.locator('[name=warehouse_id]').selectOption({label:'G-UI · Gudang uji'});
    await kitchenForm.getByRole('button',{name:'Simpan dapur'}).click();
    await saved();
    assert.equal(await page.locator('.kitchen').count(),12);
    await page.locator('tr').filter({hasText:'Dapur uji'}).getByRole('button',{name:'Ubah',exact:true}).click();
    await kitchenForm.locator('[name=name]').fill('Dapur diperbarui');
    await kitchenForm.getByRole('button',{name:'Simpan dapur'}).click();
    await saved();
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('tr').filter({hasText:'Dapur diperbarui'}).getByRole('button',{name:'Hapus',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent==='Data berhasil dihapus.');
    assert.equal(await page.locator('.kitchen').count(),11);
    await page.locator('tr').filter({hasText:'G-UI'}).getByRole('button',{name:'Ubah',exact:true}).click();
    await warehouseForm.locator('[name=name]').fill('Gudang diperbarui');
    await warehouseForm.getByRole('button',{name:'Simpan gudang'}).click();
    await saved();
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('tr').filter({hasText:'G-UI'}).getByRole('button',{name:'Hapus',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent==='Data berhasil dihapus.');
    assert.equal(await page.locator('tr').filter({hasText:'G-UI'}).count(),0);
    await clickTab('Produk');
    await saveProduct('SMOKE-FLOUR','Tepung uji','raw','kg',null,null);
    await saveProduct('SMOKE-BREAD','Roti uji','finished','pcs',3,'D01 · Dapur 1');
    await saveProduct('SMOKE-WHITE','Putih telur uji','byproduct','kg',2,null);
    await clickTab('BOM');
    await page.locator('[name=product_id]').selectOption({label:'SMOKE-BREAD · Roti uji'});
    await page.locator('[name=output_qty]').fill('40');
    await page.getByRole('button',{name:'Tambah bahan',exact:true}).click();
    await page.locator('[name=material-product-0]').selectOption({label:'SMOKE-FLOUR · Tepung uji'});
    await page.locator('[name=material-qty-0]').fill('1');
    await page.locator('[name=material-uom-0]').fill('kg');
    await page.getByRole('button',{name:'Tambah overhead',exact:true}).click();
    await page.locator('[name=overhead-name-0]').fill('Gas');
    await page.getByRole('button',{name:'Tambah turunan',exact:true}).click();
    await page.locator('[name=byproduct-product-0]').selectOption({label:'SMOKE-WHITE · Putih telur uji'});
    await page.locator('[name=byproduct-qty-0]').fill('0.5');
    await page.getByRole('button',{name:'Simpan draft BOM'}).click();
    await saved();
    await page.getByRole('button',{name:'Aktifkan',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('BOM aktif.'));
    page.once('dialog',dialog=>dialog.accept('80'));
    await page.getByRole('button',{name:'Hitung kebutuhan'}).click();
    await page.locator('#simulation').getByRole('heading',{name:'Kebutuhan untuk 80'}).waitFor();
    assert.match(await page.locator('#simulation').innerText(),/Tepung uji/);
    await page.screenshot({path:'/tmp/inventory-bom-desktop.png',fullPage:true});

    await clickTab('Stok & pemakaian');
    const receipt=page.locator('[data-form=receipt]');
    await receipt.locator('[name=warehouse_id]').selectOption({label:'GDC · Gudang Central'});
    await receipt.locator('[name=product_id]').selectOption({label:'SMOKE-FLOUR · Tepung uji'});
    await receipt.locator('[name=qty]').fill('10');
    await receipt.locator('[name=batch_number]').fill('SMOKE-LOT');
    await receipt.locator('[name=expiry_date]').fill('2099-12-31');
    await receipt.locator('[name=unit_cost]').fill('20000');
    await receipt.locator('[name=reference]').fill('SMOKE-IN');
    await receipt.getByRole('button',{name:'Catat penerimaan'}).click();
    await saved();
    await clickTab('Transfer');
    const ship=page.locator('[data-form=ship]');
    assert.equal(await ship.getByRole('button',{name:'Cetak DO',exact:true}).isDisabled(),true);
    await ship.locator('[name=source_id]').selectOption({label:'GDC · Gudang Central'});
    await ship.locator('[name=destination_id]').selectOption({label:'G-D01 · Gudang Dapur 1'});
    await ship.locator('[name=ship-product-0]').selectOption({label:'SMOKE-FLOUR · Tepung uji'});
    await ship.locator('[name=ship-qty-0]').fill('3');
    await ship.locator('[name=document_number]').fill('SMOKE-TRF');
    await ship.locator('[name=sender_name]').fill('Andi <Pengirim>');
    await ship.locator('[name=vehicle_number]').fill('be 1234 aa');
    await ship.getByRole('button',{name:'Kirim dengan FEFO'}).click();
    await saved();
    const printButton=ship.getByRole('button',{name:'Cetak DO',exact:true});
    assert.equal(await printButton.isEnabled(),true);
    assert.equal(await ship.locator('.actions').getByRole('button').count(),2);
    assert.equal(await page.locator('#transfer-detail [data-action=print-do]').count(),0);
    await page.evaluate(()=>{window.printCalls=0;window.print=()=>{window.printCalls++;};});
    await printButton.click();
    assert.equal(await page.evaluate(()=>window.printCalls),1);
    assert.match(await page.locator('#do-print').textContent(),/SMOKE-TRF/);
    assert.equal(await page.locator('#do-print').textContent().then(t=>t.includes('Riwayat penerimaan tercatat')),false);
    const receive=page.locator('[data-form=receive-transfer]');
    assert.equal(await receive.locator('input[type=number]').inputValue(),'3.000000');
    assert.match(await page.locator('#transfer-detail').innerText(),/Tepung uji/);
    assert.ok(await receive.locator('[name=received_date]').inputValue());
    await receive.locator('[name=receiver_name]').fill('Budi');
    await receive.locator('input[type=number]').fill('2');
    await receive.getByRole('button',{name:'Konfirmasi penerimaan'}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/partial/);
    assert.equal(await page.locator('[data-form=receive-transfer] input[type=number]').inputValue(),'1.000000');
    await page.locator('#transfer-document').selectOption('');
    assert.equal(await page.locator('[data-form=receive-transfer]').count(),0);
    await page.locator('#transfer-document').selectOption({index:1});
    await page.locator('[name=receiver_name]').fill('Sari');
    await page.getByRole('button',{name:'Konfirmasi penerimaan'}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/received/);
    assert.match(await page.locator('#transfer-detail').innerText(),/Budi/);
    assert.match(await page.locator('#transfer-detail').innerText(),/Sari/);
    await page.evaluate(()=>{window.printCalls=0;window.print=()=>{window.printCalls++;};});
    await page.getByRole('button',{name:'Cetak DO',exact:true}).click();
    assert.equal(await page.evaluate(()=>window.printCalls),1);
    assert.equal(await page.locator('#do-print').isVisible(),false);
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('#do-print').isVisible(),true);
    assert.equal(await page.locator('main').isVisible(),false);
    const printed=await page.locator('#do-print').innerText();
    for(const value of ['SMOKE-TRF','Andi <Pengirim>','BE 1234 AA','Tepung uji','Budi','Sari'])assert.ok(printed.includes(value),value);
    assert.equal(await page.locator('#do-print pengirim').count(),0,'Names must be escaped');
    await page.screenshot({path:'/tmp/inventory-do-print.png',fullPage:true});
    await page.emulateMedia({media:'screen'});
    await ship.locator('[name=document_number]').fill('NEW-UNSAVED');
    assert.equal(await printButton.isDisabled(),true);
    await clickTab('Stok & pemakaian');
    assert.match(await page.locator('#content').innerText(),/SMOKE-LOT/);
    await clickTab('Purchasing / PO');
    const supplier=page.locator('[data-form=supplier]');
    await supplier.locator('[name=code]').fill('SUP-UI');
    await supplier.locator('[name=name]').fill('Supplier uji');
    await supplier.getByRole('button',{name:'Simpan supplier'}).click();
    await saved();
    const po=page.locator('[data-form=po]');
    await po.locator('[name=number]').fill('PO-UI-001');
    await po.locator('[name=supplier_id]').selectOption({label:'SUP-UI · Supplier uji'});
    await po.locator('[name=warehouse_id]').selectOption({label:'GDC · Gudang Central'});
    await po.locator('[name=po-product-0]').selectOption({label:'SMOKE-FLOUR · Tepung uji'});
    await po.locator('[name=po-qty-0]').fill('5');
    await po.locator('[name=po-price-0]').fill('5000');
    await po.getByRole('button',{name:'Simpan draft PO'}).click();
    await saved();
    await page.getByRole('button',{name:'Ajukan PO',exact:true}).click();
    await saved();
    page.once('dialog',dialog=>dialog.accept('PO diperiksa'));
    await page.getByRole('button',{name:'Setujui',exact:true}).click();
    await saved();
    const poReceipt=page.locator('[data-form=po-receipt]');
    await poReceipt.locator('[name=reference]').fill('SUP-DO-1');
    await poReceipt.locator('[name=receiver_name]').fill('Penerima PO');
    await poReceipt.locator('[name=receive-qty-0]').fill('2');
    await poReceipt.locator('[name=receive-batch-0]').fill('PO-LOT-1');
    await poReceipt.locator('[name=receive-expiry-0]').fill('2099-12-31');
    await poReceipt.getByRole('button',{name:'Simpan penerimaan PO'}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/Diterima sebagian/);
    await poReceipt.locator('[name=reference]').fill('SUP-DO-2');
    await poReceipt.locator('[name=receiver_name]').fill('Penerima PO');
    await poReceipt.locator('[name=receive-qty-0]').fill('3');
    await poReceipt.locator('[name=receive-batch-0]').fill('PO-LOT-2');
    await poReceipt.locator('[name=receive-expiry-0]').fill('2099-12-31');
    await poReceipt.getByRole('button',{name:'Simpan penerimaan PO'}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/Diterima seluruhnya/);
    await page.screenshot({path:'/tmp/inventory-po.png',fullPage:true});
    await clickTab('Scrap');
    const scrap=page.locator('[data-form=request-scrap]');
    await scrap.locator('[name=number]').fill('SC-UI-001');
    await scrap.locator('[name=warehouse_id]').selectOption({label:'GDC · Gudang Central'});
    await scrap.locator('[name=reason]').fill('Kemasan rusak');
    await scrap.locator('[name=scrap-balance-0]').selectOption({index:1});
    await scrap.locator('[name=scrap-qty-0]').fill('1');
    await scrap.getByRole('button',{name:'Ajukan scrap',exact:true}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/Menunggu persetujuan/);
    page.once('dialog',dialog=>dialog.accept('Barang rusak diperiksa'));
    await page.getByRole('button',{name:'Setujui',exact:true}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/Diposting/);
    await clickTab('Opname');
    const startCount=page.locator('[data-form=start-opname]');
    await startCount.locator('[name=number]').fill('OP-UI-001');
    await startCount.locator('[name=warehouse_id]').selectOption({label:'GDC · Gudang Central'});
    await startCount.getByRole('button',{name:'Mulai hitung & kunci gudang'}).click();
    await saved();
    const countForm=page.locator('[data-form=opname-count]');
    for(const input of await countForm.locator('input[name^="count-"]').all())await input.fill('1');
    await countForm.locator('[name=counted_by]').fill('Petugas hitung');
    await countForm.locator('[name=reason]').fill('Hasil hitung fisik');
    await countForm.getByRole('button',{name:'Tambah lot temuan'}).click();
    await countForm.locator('[name=extra-product-0]').selectOption({label:'SMOKE-FLOUR · Tepung uji'});
    await countForm.locator('[name=extra-batch-0]').fill('FOUND-UI');
    await countForm.locator('[name=extra-expiry-0]').fill('2099-12-31');
    await countForm.locator('[name=extra-qty-0]').fill('1');
    await countForm.locator('[name=extra-cost-0]').fill('5000');
    await countForm.getByRole('button',{name:'Ajukan hasil opname'}).click();
    await saved();
    page.once('dialog',dialog=>dialog.accept('Selisih diperiksa'));
    await page.getByRole('button',{name:'Setujui',exact:true}).click();
    await saved();
    assert.match(await page.locator('#content').innerText(),/Diposting/);
    await page.screenshot({path:'/tmp/inventory-opname.png',fullPage:true});
    await clickTab('Stok & pemakaian');
    assert.match(await page.locator('#content').innerText(),/FOUND-UI/);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/inventory-stock-mobile.png',fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
    assert.equal(overflow,false,'Page should not overflow on mobile');
    assert.deepEqual(errors,[]);
    console.log('Browser smoke passed: activate, warehouse/kitchen CRUD, 11 kitchens, product/BOM, simulation, receipt, partial/full transfer, PO approval/partial receipts, scrap, opname with discovered lot, mobile layout.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});

